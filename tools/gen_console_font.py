#!/usr/bin/env python3
"""Generate drivers/console_font.cpp: anti-aliased DejaVu Sans Mono glyph
coverage (ASCII 32..126) on a fixed 9x18 cell. DejaVu fonts are free
(Bitstream Vera / DejaVu license, see docs/THIRD_PARTY_NOTICES.md).
Usage: python3 tools/gen_console_font.py [path-to-DejaVuSansMono.ttf]"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H, SIZE = 9, 18, 15
path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
font = ImageFont.truetype(path, SIZE)
ascent, descent = font.getmetrics()
top = (H - (ascent + descent)) // 2
rows = []
for code in range(32, 127):
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, top), chr(code), font=font, fill=255)
    px = list(img.getdata())
    rows.append(px)
out = ['#include "console_font.h"', '',
       '/* Generated by tools/gen_console_font.py - DejaVu Sans Mono, %dx%d cell, 8-bit coverage. */' % (W, H),
       'const uint8_t console_font_glyphs[CONSOLE_FONT_GLYPHS][CONSOLE_FONT_W * CONSOLE_FONT_H] = {']
for code, px in zip(range(32, 127), rows):
    body = ",".join(str(v) for v in px)
    out.append("    /* '%s' */ {%s}," % (chr(code).replace("\\", "\\\\").replace("*/", "* /"), body))
out.append("};")
open("drivers/console_font.cpp", "w").write("\n".join(out) + "\n")
print("ok", W, H, ascent, descent)
